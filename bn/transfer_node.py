"""Outcome node with a transport prior attached to the joint network (M3).

The outcome Y (acceptance of recycled plastic in food-contact packaging) is not
measured in CIS 3391. It enters the network as a child of the five transfer
predictors, with a conditional probability table generated by the transfer model:

    P(Y = 1 | x) = Phi(c + delta + sum_j b_j x_j),     b_j = s a_j beta_j + eta_j

    beta_j ~ N(beta_hat_j, se_j^2)    published Finnish coefficients (Ruokamo et al. 2022)
    a_j                               predictor-specific attenuation (ISSP, all pairs)
    s      ~ N(1, sd_s^2)             common scale uncertainty of the attenuations
    eta_j  ~ N(0, (k tau_beta)^2)     coefficient transport error (ISSP, Finland-Spain)
    delta  ~ N(0, (k tau_level)^2)    level transport error on the probit scale
    c                                 calibrated so that the population mean equals p0
    p0     ~ Beta(0.38 n0 + 0.5, 0.62 n0 + 0.5), n0 = 301

The transport layer is a hierarchical prior: tau_beta and tau_level are
between-country standard deviations estimated on ISSP proxy outcomes, and k is the
inflation that M5 calibrates out of region (k = 1 is the uncalibrated prior).

For every posterior draw (G, theta) of the CIS network a synthetic population is
drawn from the network, so the projection carries the uncertainty of the network,
of its parameters and of the missing answers, as well as the transport uncertainty.

Local data. When a first local sample (x_i, y_i) is collected, the draws are
reweighted by their likelihood prod_i P_m(y_i | x_i) (sampling importance
resampling), which is the posterior of the hierarchical model given the local data.
The equivalence between this hierarchical prior and a power prior that discounts the
source data (Chen and Ibrahim 2006) makes the discount explicit: the transport
variances fix how many local respondents the transferred evidence is worth.

Usage
  python -m bn.transfer_node                        # reads bn_cis_output/cis_joint_posterior.pkl
  python -m bn.transfer_node --k 1.67               # with the out-of-region inflation
"""
from __future__ import annotations

import argparse
import json
import pickle
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.optimize import brentq
from scipy.stats import norm

from bn.core import forward_sample

PREDICTORS = ("female", "under_30", "high_education", "recycles", "env_worry")
PARENT_VARS = ("SEX", "BIRTH", "ESTUDIOS", "V52", "V15")
P0, P0_N = 0.38, 301


def predictor_maps(coding: dict) -> dict:
    """Value of each transfer predictor for each category of its network node."""
    def lab(v):
        return coding[v]
    return {
        "female": np.array([1.0 if l.split("+")[0] == "2" else 0.0 for l in lab("SEX")]),
        "under_30": np.array([1.0 if l == "18-29" else 0.0 for l in lab("BIRTH")]),
        "high_education": np.array([1.0 if l.startswith("7") else 0.0 for l in lab("ESTUDIOS")]),
        "recycles": np.array([1.0 if l.split("+")[0] in ("1", "2") else 0.0 for l in lab("V52")]),
        # centred worry score: (V15 - 3) / 2 in [-1, 1]
        "env_worry": np.array([(float(l.split("+")[0]) - 3.0) / 2.0 for l in lab("V15")]),
    }


def design(Y: np.ndarray, names: list, maps: dict) -> np.ndarray:
    return np.column_stack([maps[p][Y[:, names.index(v)]] for p, v in zip(PREDICTORS, PARENT_VARS)])


def calibrate(linear: np.ndarray, p0: float) -> float:
    return brentq(lambda c: norm.cdf(c + linear).mean() - p0, -10, 10)


def load_transport(coef_csv: Path, issp_json: Path, att_json: Path, hier_json: Path | None = None,
                   kind: str = "cross") -> dict:
    """Transport layer. Default: Finland-Spain estimates with predictor-specific
    attenuations. With hier_json (written by bn/validate_issp.py): the hierarchical
    hyperparameters estimated on all ISSP country pairs for the given kind of
    transfer ('cross': another country and another item, as in the application)."""
    t = pd.read_csv(coef_csv).set_index("predictor").loc[list(PREDICTORS)]
    if hier_json is not None:
        h = json.loads(hier_json.read_text())[kind]
        return {"beta": t["coefficient"].to_numpy(float), "se": t["std_error"].to_numpy(float),
                "a": np.full(len(PREDICTORS), h["a_mean"]), "sd_s": h["a_sd"] / h["a_mean"],
                "tau_beta": h["tau_beta"], "tau_level": h["tau_level"]}
    issp = json.loads(issp_json.read_text())
    att = json.loads(att_json.read_text())["attenuation"]
    return {
        "beta": t["coefficient"].to_numpy(float), "se": t["std_error"].to_numpy(float),
        "a": np.array([att[p] for p in PREDICTORS]),
        "sd_s": issp["a0_fi_es"]["sd"] / issp["a0_fi_es"]["estimate"],
        "tau_beta": issp["coefficient_residual_fi_es"]["transport_sd"],
        "tau_level": issp["level_rms_fi_es"],
    }


def draw_transport(T: dict, k: float, rng) -> tuple[np.ndarray, float, float]:
    beta = rng.normal(T["beta"], T["se"])
    b = rng.normal(1.0, T["sd_s"]) * T["a"] * beta + rng.normal(0.0, k * T["tau_beta"], len(beta))
    delta = rng.normal(0.0, k * T["tau_level"])
    p0 = rng.beta(P0 * P0_N + 0.5, (1 - P0) * P0_N + 0.5)
    return b, delta, p0


SEGMENTS = {
    "All residents": lambda x, Y, n: np.ones(len(x), bool),
    "Women": lambda x, Y, n: x[:, 0] == 1,
    "Men": lambda x, Y, n: x[:, 0] == 0,
    "Under 30": lambda x, Y, n: x[:, 1] == 1,
    "30 and over": lambda x, Y, n: x[:, 1] == 0,
    "Higher education": lambda x, Y, n: x[:, 2] == 1,
    "Below higher education": lambda x, Y, n: x[:, 2] == 0,
    "Recycles always or often": lambda x, Y, n: x[:, 3] == 1,
    "Recycles sometimes or never": lambda x, Y, n: x[:, 3] == 0,
    "Extremely worried (V15 = 5)": lambda x, Y, n: x[:, 4] == 1,
    "Not at all worried (V15 = 1)": lambda x, Y, n: x[:, 4] == -1,
}
GAPS = {
    "women - men": ("Women", "Men"),
    "under 30 - 30 and over": ("Under 30", "30 and over"),
    "higher - below higher education": ("Higher education", "Below higher education"),
    "recycles often - rarely": ("Recycles always or often", "Recycles sometimes or never"),
    "extremely - not at all worried": ("Extremely worried (V15 = 5)", "Not at all worried (V15 = 1)"),
}


def project(post: dict, T: dict, k: float, n_pop: int, rng, extra: list[str] | None = None):
    """One transport draw per network draw; returns per-draw segment shares and the
    outcome table P(Y=1 | parent configuration) for each draw."""
    names, arity, coding = post["names"], np.asarray(post["arity"]), post["coding"]
    maps = predictor_maps(coding)
    pidx = [names.index(v) for v in PARENT_VARS]
    # every configuration of the five parent nodes, for the outcome table
    grid = np.array(np.meshgrid(*[np.arange(arity[j]) for j in pidx], indexing="ij")).reshape(len(pidx), -1).T
    xg = np.column_stack([maps[p][grid[:, i]] for i, p in enumerate(PREDICTORS)])
    rows, tables = [], []
    for dag, cpts in zip(post["dags"], post["cpts"]):
        Y = forward_sample(dag, cpts, arity, n_pop, rng)
        x = design(Y, names, maps)
        b, delta, p0 = draw_transport(T, k, rng)
        lin = x @ b
        c = calibrate(lin, p0) + delta
        p = norm.cdf(c + lin)
        row = {s: float(p[f(x, Y, names)].mean()) for s, f in SEGMENTS.items()}
        for v in extra or []:
            j = names.index(v)
            for cat in range(arity[j]):
                m = Y[:, j] == cat
                row[f"{v}={coding[v][cat]}"] = float(p[m].mean()) if m.any() else np.nan
        rows.append(row)
        tables.append(norm.cdf(c + xg @ b))
    draws = pd.DataFrame(rows)
    for g, (s1, s2) in GAPS.items():
        draws[g] = draws[s1] - draws[s2]
    return draws, np.array(tables), grid


def summarise(draws: pd.DataFrame, weights: np.ndarray | None = None) -> pd.DataFrame:
    w = np.ones(len(draws)) if weights is None else weights
    w = w / w.sum()
    out = []
    for c in draws.columns:
        v = draws[c].to_numpy()
        o = np.argsort(v); cw = np.cumsum(w[o])
        q = lambda a: float(v[o][np.searchsorted(cw, a)])
        out.append({"quantity": c, "mean": float(np.sum(w * v)), "low": q(0.025), "high": q(0.975)})
    return pd.DataFrame(out)


def local_update_weights(tables: np.ndarray, cfg_index: np.ndarray, y: np.ndarray) -> np.ndarray:
    """Importance weights of the draws given local data: cfg_index[i] is the row of
    the outcome table for respondent i, y[i] in {0, 1}."""
    p = np.clip(tables[:, cfg_index], 1e-12, 1 - 1e-12)
    ll = (y * np.log(p) + (1 - y) * np.log(1 - p)).sum(1)
    w = np.exp(ll - ll.max())
    return w / w.sum()


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--posterior", type=Path, default=Path("bn_cis_output/cis_joint_posterior.pkl"))
    ap.add_argument("--coefficients", type=Path, default=Path("transfer_coefficients.csv"))
    ap.add_argument("--issp", type=Path, default=Path("transport_output/issp_transport.json"))
    ap.add_argument("--attenuation", type=Path, default=Path("transport_output/attenuation_by_predictor.json"))
    ap.add_argument("--k", type=float, default=1.0, help="inflation of the transport SDs")
    ap.add_argument("--hier", type=Path, default=None,
                    help="transport_output/hierarchical_transport.json from bn/validate_issp.py")
    ap.add_argument("--n-pop", type=int, default=20000)
    ap.add_argument("--extra", nargs="*", default=["URBRURAL", "V26", "V27", "BIRTH"],
                    help="other network variables to break the projection down by")
    ap.add_argument("--seed", type=int, default=40)
    ap.add_argument("--out", type=Path, default=Path("bn_cis_output"))
    a = ap.parse_args()
    rng = np.random.default_rng(a.seed)
    post = pickle.loads(a.posterior.read_bytes())
    T = load_transport(a.coefficients, a.issp, a.attenuation, a.hier)
    extra = [v for v in a.extra if v in post["names"]]
    print(f"{len(post['dags'])} network draws; k = {a.k}; tau_beta = {a.k * T['tau_beta']:.3f}, "
          f"tau_level = {a.k * T['tau_level']:.3f}; attenuations {dict(zip(PREDICTORS, T['a']))}")
    draws, tables, grid = project(post, T, a.k, a.n_pop, rng, extra)
    s = summarise(draws)
    pd.set_option("display.width", 160)
    print("\nprojected acceptance (posterior predictive mean, 95% interval, points):")
    print((s.set_index("quantity") * 100).round(1).to_string())
    tag = f"k{a.k:g}" + ("_hier" if a.hier else "")
    s.to_csv(a.out / f"transfer_node_summary_{tag}.csv", index=False)
    np.savez_compressed(a.out / f"transfer_node_tables_{tag}.npz", tables=tables, grid=grid)
    print(f"\n-> {a.out}/transfer_node_summary_{tag}.csv (aggregate; can be committed)")


if __name__ == "__main__":
    main()
